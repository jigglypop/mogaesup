_LOCK = RLock()


class StudioPrompts:
    def __init__(self, factory, owner):
        self.path = factory.root/str(int(owner))/'library'/'prompts.json'

    def _record(self):
        # Capability screens can show built-ins before storage is configured.
        if not os.getenv('ASSET_S3_BUCKET', '').strip():
            return {'revision': '0', 'overrides': {}}
        return read_json(self.path, {'revision': '0', 'overrides': {}})

    def snapshot(self):
        record = self._record()
        return {group: {key: record['overrides'].get(f'{group}.{key}', value)
                        for key, value in values.items()} for group, values in DEFAULTS.items()}

    def values(self, group):
        return self.snapshot()[group]

    def listing(self, record=None):
        record = self._record() if record is None else record
        return {'revision': record['revision'], 'updated_at': record.get('updated_at'),
                'can_save': bool(os.getenv('ASSET_S3_BUCKET', '').strip()),
                'groups': [{'id': group, 'title': title, 'rule': rule, 'items': [
                    {'id': f'{group}.{key}', 'key': key, 'title': LABELS[key], 'default': default,
                     'value': record['overrides'].get(f'{group}.{key}', default), 'max_length': limit,
                     'customized': f'{group}.{key}' in record['overrides']}
                    for key, default in DEFAULTS[group].items()]}
                    for group, (title, limit, rule) in GROUPS.items()]}

    def save(self, changes, revision):
        if not os.getenv('ASSET_S3_BUCKET', '').strip():
            raise PipelineError('storage_required', 'S3 저장소 설정이 필요합니다.', 503)
        allowed = {f'{group}.{key}': GROUPS[group][1] for group, values in DEFAULTS.items() for key in values}
        if not changes or set(changes) - allowed.keys():
            raise PipelineError('invalid_prompt', '수정할 프롬프트를 선택하세요.', 422)
        cleaned = {}
        for key, value in changes.items():
            if value is not None and (not isinstance(value, str) or not 1 <= len(value.strip()) <= allowed[key]):
                raise PipelineError('invalid_prompt', f'프롬프트는 1~{allowed[key]}자로 입력하세요.', 422)
            group, name = key.split('.')
            value = value.strip() if value is not None else None
            cleaned[key] = None if value == DEFAULTS[group][name] else value
        with _LOCK:
            record = self._record()
            overrides = dict(record['overrides'])
            for key, value in cleaned.items():
                if value is None:
                    overrides.pop(key, None)
                else:
                    overrides[key] = value
            # Replaying a save after a lost response must not require another edit.
            if overrides == record['overrides']:
                return self.listing(record)
            if record['revision'] != revision:
                raise PipelineError('revision_conflict', '다른 화면에서 프롬프트가 변경되었습니다. 최신 내용을 불러온 뒤 다시 저장하세요.', 409)
            record = {'overrides': overrides, 'updated_at': now()}
            record['revision'] = hashlib.sha256(json.dumps(record, sort_keys=True).encode()).hexdigest()
            self.path.parent.mkdir(parents=True, exist_ok=True)
            _write_json(self.path, record)
            return self.listing(record)
