#[cfg(test)]
mod tests {
    use super::WORDS;
    use std::collections::HashSet;

    #[test]
    fn the_bank_holds_two_hundred_different_words_of_one_to_six_hangul_syllables() {
        assert!(WORDS.len() >= 200, "{} words", WORDS.len());
        let mut seen = HashSet::new();
        for word in WORDS {
            assert!(seen.insert(*word), "{word} is listed twice");
            let syllables = word.chars().count();
            assert!((1..=6).contains(&syllables), "{word}");
            assert!(word.chars().all(|c| ('\u{AC00}'..='\u{D7A3}').contains(&c)), "{word} is not all Hangul syllables");
        }
    }
}
